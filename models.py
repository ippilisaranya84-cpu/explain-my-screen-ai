
"""
ExplainMyScreen AI — Pydantic data models

Defines request and response schemas used by the FastAPI backend.
"""

from typing import Literal

from pydantic import BaseModel, Field, ConfigDict


# --------------------------------------------------
# Screenshot analysis request
# --------------------------------------------------

class ScreenAnalysisRequest(BaseModel):
    """Settings for a screenshot analysis request."""

    model_config = ConfigDict(
        str_strip_whitespace=True,
        extra="forbid",
    )

    user_question: str = Field(
        default="Explain this screen to me.",
        min_length=1,
        max_length=1000,
        description="Question or task the user wants help with.",
    )

    explanation_style: Literal[
        "beginner",
        "concise",
        "technical",
    ] = Field(
        default="beginner",
        description="Level of detail for the explanation.",
    )

    language: str = Field(
        default="English",
        min_length=2,
        max_length=50,
        description="Language to use for the explanation.",
    )


# --------------------------------------------------
# Screenshot metadata
# --------------------------------------------------

class ScreenshotInfo(BaseModel):
    """Metadata about an uploaded screenshot."""

    filename: str = Field(
        ...,
        description="Name of the screenshot file.",
    )

    width: int = Field(
        ...,
        gt=0,
        description="Screenshot width in pixels.",
    )

    height: int = Field(
        ...,
        gt=0,
        description="Screenshot height in pixels.",
    )

    format: Literal["PNG", "JPEG", "WEBP"] = Field(
        ...,
        description="Detected image format.",
    )


# --------------------------------------------------
# Screenshot analysis response
# --------------------------------------------------

class ScreenAnalysisResponse(BaseModel):
    """Result returned by the screenshot analysis endpoint."""

    success: bool = Field(
        ...,
        description="Whether screenshot analysis succeeded.",
    )

    explanation: str = Field(
        default="",
        description="Explanation generated by the AI model.",
    )

    error: str | None = Field(
        default=None,
        description="Error message, if analysis failed.",
    )

    style: str = Field(
        default="beginner",
        description="Explanation style used.",
    )

    language: str = Field(
        default="English",
        description="Language requested for the explanation.",
    )

    screenshot: ScreenshotInfo | None = Field(
        default=None,
        description="Screenshot metadata, if available.",
    )


# --------------------------------------------------
# Explanation feedback
# --------------------------------------------------

class ExplanationFeedback(BaseModel):
    """User feedback about an AI-generated explanation."""

    model_config = ConfigDict(
        str_strip_whitespace=True,
        extra="forbid",
    )

    rating: Literal[
        "helpful",
        "partially_helpful",
        "not_helpful",
    ] = Field(
        ...,
        description="How useful the explanation was.",
    )

    comment: str | None = Field(
        default=None,
        max_length=1000,
        description="Optional feedback from the user.",
    )


# --------------------------------------------------
# Health check response
# --------------------------------------------------

class HealthResponse(BaseModel):
    """Response for the backend health endpoint."""

    status: Literal["ok", "error"] = "ok"

    service: str = "ExplainMyScreen AI"

    version: str = "1.0.0"

    model: str = "gemma3:4b"
